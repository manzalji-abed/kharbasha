let lang = 'en';

export function getLang() {
  return lang;
}

export function setLang(next) {
  lang = DICT[next] ? next : 'en';
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll('[data-i18n-ph]')) el.placeholder = t(el.dataset.i18nPh);
  for (const el of document.querySelectorAll('[data-i18n-title]')) el.title = el.ariaLabel = t(el.dataset.i18nTitle);
}

// Parameters are wrapped in bidi isolates so an English name inside an Arabic sentence
// (or the reverse) doesn't scramble the word order.
export function t(key, params = {}) {
  const text = DICT[lang][key] ?? DICT.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, k) => `⁨${params[k] ?? ''}⁩`);
}
